import { useEffect, useState } from 'react'
import { useNavigate } from 'react-router-dom'

export default function Result() {
  const navigate = useNavigate()
  const [result, setResult] = useState('')
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState('')

  useEffect(() => {
    const answers = JSON.parse(localStorage.getItem('chyurum_answers') || '{}')
    if (!Object.keys(answers).length) {
      navigate('/')
      return
    }
    generateRoadmap(answers)
  }, [])
function downloadPDF() {
  const content = document.getElementById('spec-content')
  const printWindow = window.open('', '_blank')
  printWindow.document.write(`
    <html>
      <head>
        <title>Chyurum Studio — Project Roadmap</title>
        <style>
          body { font-family: Georgia, serif; max-width: 800px; margin: 40px auto; padding: 0 20px; color: #111; line-height: 1.7; }
          h1 { color: #6d28d9; font-size: 28px; margin-bottom: 4px; }
          h2 { color: #6d28d9; font-size: 20px; margin-top: 36px; padding-bottom: 8px; border-bottom: 1px solid #e5e7eb; }
          h3 { color: #111; font-size: 16px; margin-top: 20px; }
          p, li { font-size: 14px; color: #374151; }
          li { margin-bottom: 4px; }
          .header { margin-bottom: 32px; padding-bottom: 16px; border-bottom: 2px solid #6d28d9; }
          .footer { margin-top: 40px; padding-top: 16px; border-top: 1px solid #e5e7eb; color: #6d28d9; font-style: italic; }
        </style>
      </head>
      <body>
        <div class="header">
          <h1>Chyurum Studio</h1>
          <p style="color:#6b7280; margin:0;">Project Roadmap — Generated by Chyuru AI</p>
        </div>
        ${content.innerHTML}
        <div class="footer">— Chyuru, Chyurum Studio AI</div>
      </body>
    </html>
  `)
  printWindow.document.close()
  printWindow.focus()
  setTimeout(() => {
    printWindow.print()
    printWindow.close()
  }, 500)
}
  async function generateRoadmap(answers) {
    const apiKey = import.meta.env.VITE_GROQ_API_KEY

    const prompt = `
You are Chyuru, the AI project architect at Chyurum Studio.
A client has answered 10 questions about their project idea.
Generate a complete, professional project spec document based on their answers.

CLIENT ANSWERS:
1. Core idea: ${answers[1] || 'Not provided'}
2. Target audience: ${answers[2] || 'Not provided'}
3. Problem it solves: ${answers[3] || 'Not provided'}
4. Type of product: ${answers[4] || 'Not provided'}
5. Must-have features: ${answers[5] || 'Not provided'}
6. Design preferences: ${answers[6] || 'Not provided'}
7. Budget range: ${answers[7] || 'Not provided'}
8. Timeline: ${answers[8] || 'Not provided'}
9. Existing brand/assets: ${answers[9] || 'Not provided'}
10. Technical preference: ${answers[10] || 'Not provided'}

Generate a full spec document with these exact sections:

# Project Overview
[2-3 sentences about the project name, concept and goal]

# Target Audience
[Who it's for and why they need it]

# Core Features (MVP)
[List each feature with a short description]

# Pages & Screens
[Full list of every page or screen needed]

# Tech Stack Recommendation
[Frontend, Backend, Database, Hosting, APIs]

# Estimated Timeline
[Phase by phase delivery plan]

# Estimated Cost Range
[Low / Mid / High estimate broken into phases]

# Next Steps
[3 clear actions the client can take right now]

Keep it professional, clear, and encouraging. Sign off as: — Chyuru, Chyurum Studio AI
`

    try {
      const response = await fetch('https://api.groq.com/openai/v1/chat/completions', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'Authorization': `Bearer ${apiKey}`
        },
        body: JSON.stringify({
          model: 'llama-3.3-70b-versatile',
          messages: [
            {
              role: 'user',
              content: prompt
            }
          ],
          temperature: 0.7,
          max_tokens: 2000
        })
      })

      const data = await response.json()
      const text = data.choices?.[0]?.message?.content

      if (text) {
        setResult(text)
      } else {
        setError('Something went wrong. Please try again.')
        console.error('Groq response:', data)
      }
    } catch (err) {
      setError('Could not connect to Groq. Check your API key in .env file.')
      console.error('Fetch error:', err)
    } finally {
      setLoading(false)
    }
  }

  function formatResult(text) {
    const lines = text.split('\n')
    return lines.map((line, i) => {
      if (line.startsWith('# ')) {
        return (
          <h2 key={i} className="text-xl font-bold text-purple-400 mt-8 mb-3 border-b border-gray-800 pb-2">
            {line.replace('# ', '')}
          </h2>
        )
      }
      if (line.startsWith('## ')) {
        return (
          <h3 key={i} className="text-lg font-semibold text-white mt-5 mb-2">
            {line.replace('## ', '')}
          </h3>
        )
      }
      if (line.startsWith('- ') || line.startsWith('* ')) {
        return (
          <li key={i} className="text-gray-300 ml-4 mb-1 list-disc">
            {line.replace(/^[-*] /, '')}
          </li>
        )
      }
      if (line.startsWith('**') && line.endsWith('**')) {
        return (
          <p key={i} className="text-white font-semibold mt-3 mb-1">
            {line.replace(/\*\*/g, '')}
          </p>
        )
      }
      if (line.trim() === '') {
        return <br key={i} />
      }
      return (
        <p key={i} className="text-gray-300 mb-2 leading-relaxed">
          {line}
        </p>
      )
    })
  }

  if (loading) {
    return (
      <div className="min-h-screen bg-gray-950 flex flex-col items-center justify-center text-white">
        <div className="w-12 h-12 border-2 border-purple-500 border-t-transparent rounded-full animate-spin mb-6"></div>
        <h2 className="text-xl font-semibold mb-2">Chyuru is crafting your roadmap...</h2>
        <p className="text-gray-500 text-sm">This takes about 5–10 seconds</p>
      </div>
    )
  }

  if (error) {
    return (
      <div className="min-h-screen bg-gray-950 flex flex-col items-center justify-center text-white px-6">
        <div className="text-red-400 text-5xl mb-4">⚠</div>
        <h2 className="text-xl font-semibold mb-2">Something went wrong</h2>
        <p className="text-gray-400 text-sm mb-6 text-center max-w-md">{error}</p>
        <button
          onClick={() => navigate('/')}
          className="bg-purple-600 hover:bg-purple-500 text-white px-6 py-2.5 rounded-lg text-sm transition-all"
        >
          ← Start over
        </button>
      </div>
    )
  }

  return (
    <div className="min-h-screen bg-gray-950 text-white">
      <div className="border-b border-gray-800 px-6 py-4 flex items-center justify-between">
        <span className="text-purple-400 font-semibold">Chyurum Studio</span>
        <div className="flex gap-3">
          <button
            onClick={downloadPDF}
            className="text-sm border border-gray-700 hover:border-purple-500 text-gray-300 hover:text-white px-4 py-2 rounded-lg transition-all"
          >
            Print / Save PDF
          </button>
          <button
            onClick={() => navigate('/')}
            className="text-sm bg-purple-600 hover:bg-purple-500 text-white px-4 py-2 rounded-lg transition-all"
          >
            New project
          </button>
        </div>
      </div>

      <div className="max-w-3xl mx-auto px-6 py-10">
        <div className="inline-flex items-center gap-2 bg-purple-900/40 border border-purple-700/50 rounded-full px-4 py-1.5 text-purple-300 text-sm mb-6">
          ✦ Your project roadmap is ready
        </div>

        <div id="spec-content" className="prose prose-invert max-w-none">
          {formatResult(result)}
        </div>

        <div className="mt-12 pt-8 border-t border-gray-800 flex flex-col sm:flex-row gap-3">
          <button
            onClick={() => window.print()}
            className="flex-1 border border-gray-700 hover:border-purple-500 text-gray-300 hover:text-white py-3 rounded-xl text-sm transition-all"
          >
            Print / Save as PDF
          </button>
          <button
            onClick={() => {
              navigator.clipboard.writeText(result)
              alert('Copied to clipboard!')
            }}
            className="flex-1 border border-gray-700 hover:border-purple-500 text-gray-300 hover:text-white py-3 rounded-xl text-sm transition-all"
          >
            Copy to clipboard
          </button>
          <button
            onClick={() => navigate('/')}
            className="flex-1 bg-purple-600 hover:bg-purple-500 text-white py-3 rounded-xl text-sm transition-all"
          >
            Start new project →
          </button>
        </div>
      </div>
    </div>
  )
}